// OpenAI 이미지 편집 API로, 쿠팡 공식 스튜디오컷을 "실제 사람이 쓰는/먹는 순간을 찍은" 것처럼 바꾼다.
// 벤치마킹한 파트너스 계정들(살림보물창고, 제나템)이 전부 이런 "진짜 찍은 것 같은" 사진을 쓰길래
// 도입한 기능 — 얼굴 없이, 스마트폰 후기 사진 느낌으로 편집한다.
//
// 필요: OPENAI_API_KEY (.env) — ChatGPT 구독과는 별개로 발급받아야 한다.
// 설정 안 돼 있으면 이 모듈을 쓰는 쪽에서 조용히 건너뛰고 원본 쿠팡 이미지를 그대로 쓴다.

const MODEL = "gpt-image-1.5";

function isConfigured() {
  return Boolean(process.env.OPENAI_API_KEY);
}

async function editImage(inputBuffer, prompt, { size = "1024x1024", quality = "medium" } = {}) {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    const err = new Error("OPENAI_API_KEY가 설정되지 않았습니다.");
    err.status = 500;
    throw err;
  }

  const form = new FormData();
  form.append("model", MODEL);
  form.append("image", new Blob([inputBuffer], { type: "image/jpeg" }), "source.jpg");
  form.append("prompt", prompt);
  form.append("size", size);
  form.append("quality", quality);
  form.append("n", "1");

  const res = await fetch("https://api.openai.com/v1/images/edits", {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}` },
    body: form,
  });
  const data = await res.json().catch(() => ({}));

  if (!res.ok) {
    const err = new Error("이미지 편집(OpenAI)에 실패했습니다: " + (data.error?.message || `HTTP ${res.status}`));
    err.status = res.status >= 400 ? res.status : 502;
    throw err;
  }
  const b64 = data.data?.[0]?.b64_json;
  if (!b64) throw new Error("이미지 편집 응답에 결과가 없습니다: " + JSON.stringify(data).slice(0, 300));
  return Buffer.from(b64, "base64");
}

