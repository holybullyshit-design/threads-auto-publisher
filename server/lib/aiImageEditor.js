async function generateAuthenticPhotos(rawBuffer, { context } = {}) {
  const kinds = Object.keys(PROMPTS); // 항상 정확히 2개(hold, result) — count 매개변수로 늘리지 않는다
  const results = await Promise.allSettled(
    kinds.map((kind) => editImage(rawBuffer, PROMPTS[kind](context)))
  );
  return results.filter((r) => r.status === "fulfilled").map((r) => r.value);
}

