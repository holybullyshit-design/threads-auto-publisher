function applyEdition(pkg) {
  const e = editions[pkg.date];
  if (!e) return false;
  if (pkg.calendar.day !== e.day || pkg.calendar.year !== '丙午' || pkg.calendar.month !== '丙申') throw new Error('검수된 9월 일진과 계산 결과가 다릅니다.');
  const seen = new Set();
  for (const [i, r] of pkg.readings.entries()) {
    r.lines = [...e.rows[i]];
    for (const line of r.lines) { if (seen.has(line)) throw new Error('일일 문구 중복'); seen.add(line); }
    // Avoid making a deterministic promise from a two-branch relationship.
    r.easyTitle = ({'인연운 상승':'관계 조율','기회운 활짝':'함께 살피기','변화 앞 신중':'변경 점검','오해 조심':'짐작보다 확인','정리하면 풀림':'빈틈 정리','속도 조절':'말의 속도 조절','내가 주도할 날':'주도하되 조율','잔잔한 안정운':'기본 챙기기'})[r.easyTitle];
    r.easyWhy = '띠와 일진을 참고한 생활 조언';
  }
  pkg.editorial = { version:'palja-september-2026-v1', topic:e.topic, hook:e.hook, question:e.question };
  pkg.slides[0].editorial = e;
  pkg.slides[5] = { ...pkg.slides[5], fixed:false, editorial:e };
  pkg.slides[6] = { ...pkg.slides[6], fixed:false, editorial:e };
  pkg.caption = `${e.hook.join(' ')}\n${Number(pkg.date.slice(5,7))}월 ${Number(pkg.date.slice(8))}일 오늘의 띠별 운세\n\n${e.intro}\n\n오늘의 명리 포인트 — ${e.lessonTitle}\n${e.lesson.join('\n')}\n\n12띠·생년별 생활 조언은 카드 2~5장에 정리했습니다. 필요한 한 줄을 저장하고 오늘의 선택 전에 다시 살펴보세요.\n\n${e.question}\n${e.cta}\n개인 사주 상담 안내는 프로필에서 확인할 수 있습니다.\n\n※ 전통 명리의 띠·일진 관계를 참고한 생활 조언입니다. 생년별 문장은 편집한 참고 문구이며 개인 원국·재물·관계의 결과를 예측하지 않습니다. 1~2월생은 입춘에 따라 전년도 띠일 수 있습니다.\n\n${e.tags.map(t=>'#'+t).join(' ')}`;
  return true;
}

module.exports = { editions, applyEdition };
