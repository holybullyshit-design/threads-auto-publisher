// 다르게 처리하면 같은 사람 사주가 호출할 때마다 다르게 나온다. 사용자 지시(2026-10-07):
// **가장 많이 쓰는 명리학으로, 모든 풀이 답변이 일치하게.** 그래서 전부 여기 한 곳에 못 박고,
// 엔진 어디서도 이 값을 즉흥적으로 바꾸지 않는다. 바꿀 일이 생기면 이 파일과 CLAUDE.md를 같이 고친다.
//
// 결정론 원칙: 같은 입력(생년월일시·성별·달력종류)이면 **항상 같은 출력**이어야 한다.
// 엔진 안에서 Math.random()·Date.now()·현재시각 의존을 절대 쓰지 않는다(운 계산의 기준일은
// 반드시 인자로 받는다).

module.exports = {
  // ── 일주가 바뀌는 시점 ──
  // 한국 실무 주류(원광·천지인류 만세력)는 **자정(00:00) 기준으로 일주가 바뀐다**.
  // 23:00~23:59는 "야자시"로 그 날의 자시로 보고, 일주는 당일 것을 그대로 쓴다.
  // lunar-javascript의 sect 2가 이 방식이다(sect 1은 23시에 일주를 다음날로 넘긴다).
  DAY_BOUNDARY_SECT: 2,
  // lunar-javascript가 계산하는 절기 시각의 기준 시간대와 KST의 차이(분).
  // 라이브러리는 중국 표준시(UTC+8)로 절기를 계산하므로 KST(UTC+9)보다 60분 이르다.
  // 1950~2026년 절기 1,771개를 manseryeok(KASI)·k-saju(astronomy-engine)와 3자 대조해 확정했다
  // — 1,771개 전부 정확히 60분 차이였다. 라이브러리를 바꾸면 이 값부터 다시 재야 한다.
  JIEQI_TZ_OFFSET_MIN: 60,


  // ── 진태양시 보정 ──
  // 한국 표준시는 동경 135°를 쓰는데 서울은 약 127°라 실제 태양시와 약 32분 차이가 난다.
  // 보정을 적용하는 유파와 안 하는 유파가 갈리고, 한국 만세력 프로그램 대부분은 **표준시를
  // 기본**으로 하고 보정을 옵션으로 둔다. 그래서 기본값은 보정 없음(표준시 그대로)으로 고정하고,
  // 대신 보정했을 때 시주가 **바뀔 수 있는 경계**(시 경계 ±LONGITUDE_OFFSET_MIN)에 태어난
  // 경우에는 결과에 경고를 달아서, 상담에서 시주를 단정하지 않게 한다.
  APPLY_TRUE_SOLAR_TIME: false,
  LONGITUDE_OFFSET_MIN: -32, // 서울(126.978°E) 기준. 적용할 때만 쓴다.

  // ── 신강약 판정 (억부법) ──
  // 가장 널리 쓰이는 억부법: 일간을 돕는 세력(비겁+인성)과 빼는 세력(식상+재성+관성)을
  // 비교한다. 자리별 가중치는 "월지가 가장 세다"는 통설을 따르고, 지장간은 본기(本氣)를
  // 더 무겁게 본다. 이 숫자들은 유파마다 조금씩 다르므로 여기 고정해두고 임의로 바꾸지 않는다.
  STRENGTH_WEIGHTS: {
    stem: { year: 10, month: 20, day: 0, time: 10 }, // 일간 자신은 세력 집계에서 제외(기준점)
    branch: { year: 10, month: 30, day: 20, time: 10 },
    hiddenStem: { primary: 0.5, secondary: 0.3 }, // 지지 가중치에 곱해서 지장간에 배분
  },
  // 돕는 세력 비율이 이 값 이상이면 신강, 이하면 신약, 사이면 중화로 본다.
  STRENGTH_THRESHOLD: { strong: 0.55, weak: 0.45 },

  // ── 용신 ──
  // 용신 선정은 학파 차이가 가장 큰 영역이다. 엔진은 억부 기준 **후보**만 계산하고,
  // 이걸 "사실"로 단정하지 않는다(글에서도 단정 금지 - sajuClaimChecker가 막는다).
  ASSERT_YONGSIN: false,
};
